#!/usr/bin/env bash
# =============================================================================
# LOONY LINUX — Cloudflare IP ranges: real client IPs + origin lockdown
# =============================================================================
# Fetches Cloudflare's current edge IP ranges and generates:
#   --nginx     nginx config so $remote_addr is the visitor, not Cloudflare
#   --nftables  nftables table that drops HTTP/HTTPS not coming from Cloudflare
#   --ufw       UFW rules allowing HTTP/HTTPS only from Cloudflare (applied directly)
#
# Usage:
#   bash cloudflare-ips.sh --list                       Print the ranges
#   sudo bash cloudflare-ips.sh --nginx [FILE]          Default: /etc/nginx/conf.d/cloudflare-real-ip.conf
#   sudo bash cloudflare-ips.sh --nftables [FILE]       Default: /etc/nftables.d/cloudflare.nft
#   sudo bash cloudflare-ips.sh --ufw
#   Add --dry-run to print instead of writing/applying.
#
# Ranges change rarely, but they do change: re-run weekly (cron or a systemd timer).
# =============================================================================

set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
IPS_URL="https://api.cloudflare.com/client/v4/ips"
PORTS="${PORTS:-80,443}"                 # Ports to restrict to Cloudflare
NGINX_FILE_DEFAULT="/etc/nginx/conf.d/cloudflare-real-ip.conf"
NFT_FILE_DEFAULT="/etc/nftables.d/cloudflare.nft"

DRY_RUN=false

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
ts()    { date +'%Y-%m-%d %H:%M:%S'; }
log()   { echo "$(ts) $*" >&2; }
error() { echo "$(ts) [ERROR] $*" >&2; exit 1; }

usage() { sed -n '/^# Usage:/,/^# Ranges/p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

# Write stdin to a file atomically, or print it with --dry-run
emit() {
  local file="$1" tmp
  if [[ "$DRY_RUN" == true ]]; then
    echo "# --- would write: $file"
    cat
    return
  fi
  mkdir -p "$(dirname "$file")"
  tmp=$(mktemp "${file}.XXXX")
  cat > "$tmp"
  chmod 644 "$tmp"
  mv "$tmp" "$file"
  log "Wrote $file"
}

V4=() V6=()
fetch_ranges() {
  command -v jq &>/dev/null || error "Missing: jq"
  local json
  json=$(curl -sS --max-time 20 "$IPS_URL") || error "Could not fetch $IPS_URL"
  [[ "$(jq -r '.success' <<<"$json")" == "true" ]] || error "Unexpected response from $IPS_URL"
  mapfile -t V4 < <(jq -r '.result.ipv4_cidrs[]' <<<"$json")
  mapfile -t V6 < <(jq -r '.result.ipv6_cidrs[]' <<<"$json")
  # Refuse to lock down an origin with a suspiciously short list
  (( ${#V4[@]} >= 5 && ${#V6[@]} >= 3 )) || error "Got too few ranges (${#V4[@]} v4, ${#V6[@]} v6) — aborting"
  log "Fetched ${#V4[@]} IPv4 and ${#V6[@]} IPv6 ranges"
}

# ---------------------------------------------------------------------------
# Generators
# ---------------------------------------------------------------------------
gen_nginx() {
  echo "# Generated by cloudflare-ips.sh on $(date -u +%F) — do not edit by hand"
  echo "# Restores the visitor IP from CF-Connecting-IP for requests from Cloudflare."
  local c
  for c in "${V4[@]}" "${V6[@]}"; do echo "set_real_ip_from $c;"; done
  echo "real_ip_header CF-Connecting-IP;"
}

gen_nftables() {
  local ports="${PORTS//,/, }"
  cat <<EOF
#!/usr/sbin/nft -f
# Generated by cloudflare-ips.sh on $(date -u +%F) — do not edit by hand
# Drops TCP to ports { $ports } unless the source is a Cloudflare edge IP.
# Separate table: works alongside an existing ruleset (a drop here is final).

table inet cloudflare
delete table inet cloudflare

table inet cloudflare {
  set cf4 {
    type ipv4_addr; flags interval
    elements = { $(IFS=,; echo "${V4[*]}" | sed 's/,/, /g') }
  }
  set cf6 {
    type ipv6_addr; flags interval
    elements = { $(IFS=,; echo "${V6[*]}" | sed 's/,/, /g') }
  }
  chain input {
    type filter hook input priority filter; policy accept;
    iifname "lo" return
    tcp dport { $ports } ip saddr != @cf4 drop
    tcp dport { $ports } ip6 saddr != @cf6 drop
  }
}
EOF
}

apply_ufw() {
  command -v ufw &>/dev/null || error "Missing: ufw"
  local c port
  for c in "${V4[@]}" "${V6[@]}"; do
    if [[ "$DRY_RUN" == true ]]; then
      echo "ufw allow proto tcp from $c to any port $PORTS comment cloudflare"
    else
      ufw allow proto tcp from "$c" to any port "$PORTS" comment cloudflare >/dev/null
    fi
  done
  log "Allowed ports $PORTS from ${#V4[@]} + ${#V6[@]} Cloudflare ranges"
  for port in ${PORTS//,/ }; do
    log "Remove any broad rule for port $port yourself, e.g.: ufw delete allow $port/tcp"
  done
}

# ---------------------------------------------------------------------------
main() {
  local mode="" file=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --list|--nginx|--nftables|--ufw)
        mode="${1#--}"
        if [[ "${2:-}" != "" && "${2:-}" != --* ]]; then file="$2"; shift; fi
        ;;
      --dry-run) DRY_RUN=true ;;
      -h|--help) usage 0 ;;
      *) echo "Unknown option: $1" >&2; usage 1 ;;
    esac
    shift
  done
  [[ -n "$mode" ]] || usage 1
  if [[ "$mode" != list && "$DRY_RUN" == false && $EUID -ne 0 ]]; then
    error "Run as root (or use --dry-run)"
  fi

  fetch_ranges

  case "$mode" in
    list)
      printf '%s\n' "${V4[@]}" "${V6[@]}"
      ;;
    nginx)
      gen_nginx | emit "${file:-$NGINX_FILE_DEFAULT}"
      [[ "$DRY_RUN" == true ]] || log "Next: nginx -t && systemctl reload nginx"
      ;;
    nftables)
      file="${file:-$NFT_FILE_DEFAULT}"
      gen_nftables | emit "$file"
      if [[ "$DRY_RUN" == false ]]; then
        nft -c -f "$file" || error "nft rejected $file"
        log "Next: nft -f $file   (and include it from /etc/nftables.conf to persist)"
      fi
      ;;
    ufw)
      apply_ufw
      ;;
  esac
}

main "$@"
