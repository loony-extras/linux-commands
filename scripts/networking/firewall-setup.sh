#!/usr/bin/env bash
# =============================================================================
# LOONY LINUX — Firewall Setup (nftables)
# =============================================================================
# Sets up a production-grade nftables firewall.
# Profile-based: web, db, bastion, minimal
#
# Usage: sudo bash firewall-setup.sh --profile web [--ssh-port 22]
# =============================================================================

set -euo pipefail

log()   { echo "[$(date +'%H:%M:%S')] $*"; }
error() { echo "[ERROR] $*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || error "Must run as root"

PROFILE="web"
SSH_PORT="22"
MGMT_CIDR=""          # Optional: management IP range, e.g., 10.0.0.0/8

while [[ $# -gt 0 ]]; do
  case $1 in
    --profile)   PROFILE="$2"; shift 2 ;;
    --ssh-port)  SSH_PORT="$2"; shift 2 ;;
    --mgmt-cidr) MGMT_CIDR="$2"; shift 2 ;;
    *) error "Unknown argument: $1" ;;
  esac
done

# Install nftables
apt-get install -y -q nftables
systemctl enable nftables

# ---------------------------------------------------------------------------
# Build the nftables config based on profile
# ---------------------------------------------------------------------------
write_base_rules() {
cat > /etc/nftables.conf << NFTEOF
#!/usr/sbin/nft -f
# Generated by loony-linux firewall-setup.sh
# Profile: $PROFILE | $(date)

flush ruleset

table inet filter {

    # Rate-limit sets
    set ssh_ratelimit {
        type ipv4_addr
        flags dynamic, timeout
        timeout 60s
    }

    chain input {
        type filter hook input priority 0; policy drop;

        # Allow loopback
        iif lo accept

        # Allow established/related (stateful)
        ct state established, related accept

        # Drop invalid packets
        ct state invalid drop

        # ICMP (allow ping, type 8 = echo-request)
        ip protocol icmp icmp type {
            echo-request, echo-reply,
            destination-unreachable, time-exceeded, parameter-problem
        } accept

        # ICMPv6
        ip6 nexthdr icmpv6 icmpv6 type {
            echo-request, echo-reply,
            destination-unreachable, packet-too-big,
            time-exceeded, parameter-problem,
            nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert
        } accept

NFTEOF
}

write_ssh_rules() {
cat >> /etc/nftables.conf << NFTEOF
        # SSH — rate limited
        tcp dport $SSH_PORT ct state new \\
            add @ssh_ratelimit { ip saddr timeout 60s limit rate over 10/minute } \\
            drop
        tcp dport $SSH_PORT ct state new accept

NFTEOF
}

write_mgmt_rules() {
  if [[ -n "$MGMT_CIDR" ]]; then
cat >> /etc/nftables.conf << NFTEOF
        # Management network — unrestricted access
        ip saddr $MGMT_CIDR accept

NFTEOF
  fi
}

write_web_rules() {
cat >> /etc/nftables.conf << NFTEOF
        # HTTP / HTTPS
        tcp dport { 80, 443 } accept

NFTEOF
}

write_db_rules() {
cat >> /etc/nftables.conf << NFTEOF
        # Database — only from app subnet (customize CIDR)
        # PostgreSQL
        ip saddr 10.0.0.0/8 tcp dport 5432 accept
        # MySQL / MariaDB
        ip saddr 10.0.0.0/8 tcp dport 3306 accept
        # Redis
        ip saddr 10.0.0.0/8 tcp dport 6379 accept

NFTEOF
}

write_monitoring_rules() {
cat >> /etc/nftables.conf << NFTEOF
        # Prometheus node exporter (from monitoring server)
        ip saddr 10.0.0.0/8 tcp dport 9100 accept

NFTEOF
}

write_close_input() {
cat >> /etc/nftables.conf << NFTEOF
        # Log and drop everything else
        log prefix "[nft-drop] " flags all
    }

    chain forward {
        type filter hook forward priority 0; policy drop;
    }

    chain output {
        type filter hook output priority 0; policy accept;
    }
}
NFTEOF
}

# ---------------------------------------------------------------------------
# Generate rules based on profile
# ---------------------------------------------------------------------------
write_base_rules
write_mgmt_rules
write_ssh_rules
write_monitoring_rules

case "$PROFILE" in
  web)
    write_web_rules
    log "Profile: web (SSH + HTTP/HTTPS + monitoring)"
    ;;
  db)
    write_db_rules
    log "Profile: database (SSH + DB ports for internal + monitoring)"
    ;;
  bastion)
    # Bastion just needs SSH open
    log "Profile: bastion (SSH only)"
    ;;
  minimal)
    log "Profile: minimal (SSH only)"
    ;;
  *)
    error "Unknown profile: $PROFILE. Valid: web, db, bastion, minimal"
    ;;
esac

write_close_input

# ---------------------------------------------------------------------------
# Apply rules
# ---------------------------------------------------------------------------
nft -c -f /etc/nftables.conf && log "nftables config syntax OK"
systemctl restart nftables

log "Firewall active. Verify with: nft list ruleset"
echo
nft list ruleset
