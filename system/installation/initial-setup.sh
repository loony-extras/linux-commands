#!/usr/bin/env bash
# =============================================================================
# LOONY LINUX — Initial Server Setup Script
# =============================================================================
# Idempotent provisioning script for Ubuntu 22.04 / 24.04 servers.
# Run as root on a fresh install.
#
# Usage:
#   sudo bash initial-setup.sh [--hostname myserver] [--admin-user deploy]
# =============================================================================

set -euo pipefail
IFS=$'\n\t'

# ---------------------------------------------------------------------------
# Configuration (override via env or flags)
# ---------------------------------------------------------------------------
HOSTNAME="${HOSTNAME:-$(hostname -s)}"
ADMIN_USER="${ADMIN_USER:-admin}"
TIMEZONE="${TIMEZONE:-UTC}"
SSHD_PORT="${SSHD_PORT:-22}"
LOG_FILE="/var/log/loony-setup.log"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
log()     { echo -e "${GREEN}[$(date +'%H:%M:%S')]${NC} $*" | tee -a "$LOG_FILE"; }
warn()    { echo -e "${YELLOW}[WARN]${NC} $*" | tee -a "$LOG_FILE"; }
error()   { echo -e "${RED}[ERROR]${NC} $*" | tee -a "$LOG_FILE" >&2; exit 1; }
section() { echo -e "\n${GREEN}===== $* =====${NC}" | tee -a "$LOG_FILE"; }

[[ $EUID -eq 0 ]] || error "Must run as root (sudo bash $0)"

# Parse flags
while [[ $# -gt 0 ]]; do
  case $1 in
    --hostname)    HOSTNAME="$2"; shift 2 ;;
    --admin-user)  ADMIN_USER="$2"; shift 2 ;;
    --timezone)    TIMEZONE="$2"; shift 2 ;;
    --ssh-port)    SSHD_PORT="$2"; shift 2 ;;
    *) error "Unknown argument: $1" ;;
  esac
done

# ---------------------------------------------------------------------------
section "System Update"
# ---------------------------------------------------------------------------
apt-get update -qq
apt-get upgrade -y -q
apt-get autoremove -y -q

# ---------------------------------------------------------------------------
section "Core Packages"
# ---------------------------------------------------------------------------
PACKAGES=(
  # Shells and editors
  bash-completion vim tmux

  # Network tools
  curl wget net-tools dnsutils nmap netcat-openbsd
  iproute2 iputils-ping traceroute mtr-tiny

  # System tools
  htop iotop iftop sysstat lsof strace
  rsync unzip jq bc tree ncdu

  # Build essentials
  build-essential git ca-certificates gnupg lsb-release

  # Security
  ufw fail2ban auditd apparmor apparmor-utils rkhunter
  aide aide-common libpam-pwquality unattended-upgrades

  # Monitoring
  chrony logwatch

  # Storage
  lvm2 mdadm

  # Misc
  acl attr
)

apt-get install -y "${PACKAGES[@]}"

# ---------------------------------------------------------------------------
section "Hostname and Locale"
# ---------------------------------------------------------------------------
hostnamectl set-hostname "$HOSTNAME"
log "Hostname set to: $HOSTNAME"

timedatectl set-timezone "$TIMEZONE"
timedatectl set-ntp true
log "Timezone: $TIMEZONE, NTP enabled"

locale-gen en_US.UTF-8
update-locale LANG=en_US.UTF-8 LC_ALL=en_US.UTF-8

# ---------------------------------------------------------------------------
section "Admin User Setup"
# ---------------------------------------------------------------------------
if ! id "$ADMIN_USER" &>/dev/null; then
  useradd -m -s /bin/bash -G sudo,adm -c "Admin User" "$ADMIN_USER"
  # Generate a random temporary password — user must change on first login
  TEMP_PASS=$(openssl rand -base64 16)
  echo "$ADMIN_USER:$TEMP_PASS" | chpasswd
  chage -d 0 "$ADMIN_USER"     # Force password change on first login
  log "Created user: $ADMIN_USER (temp password: $TEMP_PASS)"
  warn "User $ADMIN_USER must change password on first login"
else
  usermod -aG sudo,adm "$ADMIN_USER"
  log "User $ADMIN_USER already exists; ensured sudo membership"
fi

# Create .ssh directory if not present
ADMIN_HOME=$(getent passwd "$ADMIN_USER" | cut -d: -f6)
mkdir -p "$ADMIN_HOME/.ssh"
chmod 700 "$ADMIN_HOME/.ssh"
chown -R "$ADMIN_USER:$ADMIN_USER" "$ADMIN_HOME/.ssh"

# ---------------------------------------------------------------------------
section "SSH Hardening"
# ---------------------------------------------------------------------------
cat > /etc/ssh/sshd_config.d/99-hardening.conf << EOF
# Generated by loony-linux initial-setup.sh
Port $SSHD_PORT
PermitRootLogin no
PasswordAuthentication yes          # Set to no once SSH keys are deployed
PubkeyAuthentication yes
AuthorizedKeysFile .ssh/authorized_keys
PermitEmptyPasswords no
X11Forwarding no
AllowTcpForwarding no
MaxAuthTries 3
LoginGraceTime 60
MaxStartups 10:30:60
ClientAliveInterval 300
ClientAliveCountMax 2
PrintMotd no
PrintLastLog yes
EOF

# Legal banner
cat > /etc/ssh/banner.txt << 'EOF'
***************************************************************************
  AUTHORIZED ACCESS ONLY — All activity is monitored and logged.
  Unauthorized access will be prosecuted to the full extent of the law.
  Disconnect immediately if you are not authorized.
***************************************************************************
EOF

echo "Banner /etc/ssh/banner.txt" >> /etc/ssh/sshd_config.d/99-hardening.conf

sshd -t && systemctl reload sshd
log "SSH hardened on port $SSHD_PORT"

# ---------------------------------------------------------------------------
section "Firewall (UFW)"
# ---------------------------------------------------------------------------
ufw --force reset
ufw default deny incoming
ufw default allow outgoing
ufw default deny forward

# Allow SSH first (avoid lockout)
ufw allow "$SSHD_PORT/tcp" comment "SSH"

# Rate-limit SSH to slow brute force
ufw limit "$SSHD_PORT/tcp"

ufw --force enable
log "UFW enabled. SSH port $SSHD_PORT allowed."

# ---------------------------------------------------------------------------
section "Unattended Security Upgrades"
# ---------------------------------------------------------------------------
cat > /etc/apt/apt.conf.d/50unattended-upgrades << 'EOF'
Unattended-Upgrade::Allowed-Origins {
    "${distro_id}:${distro_codename}-security";
};
Unattended-Upgrade::AutoFixInterruptedDpkg "true";
Unattended-Upgrade::MinimalSteps "true";
Unattended-Upgrade::Remove-Unused-Dependencies "true";
Unattended-Upgrade::Automatic-Reboot "false";
EOF

cat > /etc/apt/apt.conf.d/20auto-upgrades << 'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
EOF

systemctl enable --now unattended-upgrades

# ---------------------------------------------------------------------------
section "Fail2ban"
# ---------------------------------------------------------------------------
cat > /etc/fail2ban/jail.local << 'EOF'
[DEFAULT]
bantime = 600
findtime = 600
maxretry = 5
backend = systemd
ignoreip = 127.0.0.1/8 ::1

[sshd]
enabled = true
port = ssh
logpath = %(sshd_log)s
maxretry = 3
bantime = 3600
EOF

systemctl enable --now fail2ban
log "Fail2ban configured and enabled"

# ---------------------------------------------------------------------------
section "Kernel Security Parameters"
# ---------------------------------------------------------------------------
cat > /etc/sysctl.d/99-security.conf << 'EOF'
net.ipv4.ip_forward = 0
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.all.rp_filter = 1
net.ipv4.conf.default.rp_filter = 1
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.all.log_martians = 1
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.tcp_syncookies = 1
kernel.dmesg_restrict = 1
kernel.kptr_restrict = 2
kernel.yama.ptrace_scope = 2
kernel.sysrq = 0
fs.protected_hardlinks = 1
fs.protected_symlinks = 1
kernel.randomize_va_space = 2
fs.suid_dumpable = 0
net.core.somaxconn = 65535
fs.file-max = 2097152
fs.inotify.max_user_watches = 524288
EOF

sysctl -p /etc/sysctl.d/99-security.conf
log "Kernel security parameters applied"

# ---------------------------------------------------------------------------
section "Audit Daemon"
# ---------------------------------------------------------------------------
cat > /etc/audit/rules.d/99-custom.rules << 'EOF'
-D
-b 8192
-f 1
-w /etc/passwd -p wa -k identity
-w /etc/shadow -p wa -k identity
-w /etc/sudoers -p wa -k sudoers
-w /etc/sudoers.d/ -p wa -k sudoers
-w /var/log/wtmp -p wa -k session
-w /var/log/btmp -p wa -k session
-a always,exit -F arch=b64 -S execve -C uid!=euid -F euid=0 -k setuid
-w /usr/bin/sudo -p x -k sudo
-w /etc/ssh/sshd_config -p wa -k sshd_config
-w /etc/crontab -p wa -k cron
-w /etc/cron.d/ -p wa -k cron
EOF

systemctl enable --now auditd
log "auditd enabled with security rules"

# ---------------------------------------------------------------------------
section "Shell Environment"
# ---------------------------------------------------------------------------
cat > /etc/profile.d/99-loony.sh << 'EOF'
# Safer history
export HISTSIZE=10000
export HISTFILESIZE=20000
export HISTTIMEFORMAT="%F %T "
export HISTCONTROL=ignoredups:erasedups
shopt -s histappend 2>/dev/null || true

# Useful aliases
alias ll='ls -alFh'
alias la='ls -A'
alias df='df -h'
alias du='du -sh'
alias free='free -h'
alias ports='ss -tlnp'

# Safety
alias rm='rm -i'
alias cp='cp -i'
alias mv='mv -i'
EOF

# ---------------------------------------------------------------------------
section "Disable Unnecessary Services"
# ---------------------------------------------------------------------------
DISABLE_SERVICES=(avahi-daemon cups bluetooth ModemManager)
for svc in "${DISABLE_SERVICES[@]}"; do
  if systemctl is-enabled "$svc" &>/dev/null; then
    systemctl disable --now "$svc" 2>/dev/null || true
    log "Disabled: $svc"
  fi
done

# Disable Ctrl+Alt+Del reboot
systemctl mask ctrl-alt-del.target

# ---------------------------------------------------------------------------
section "Chrony (NTP)"
# ---------------------------------------------------------------------------
systemctl enable --now chrony
chronyc tracking | head -5

# ---------------------------------------------------------------------------
section "AIDE File Integrity Baseline"
# ---------------------------------------------------------------------------
if [[ ! -f /var/lib/aide/aide.db ]]; then
  log "Initializing AIDE database (this takes a while)..."
  aideinit 2>&1 | tail -3 || true
  [[ -f /var/lib/aide/aide.db.new ]] && mv /var/lib/aide/aide.db.new /var/lib/aide/aide.db
  log "AIDE database initialized"
fi

# Daily AIDE check via cron
cat > /etc/cron.daily/aide-check << 'EOF'
#!/bin/bash
/usr/bin/aide --check 2>&1 | /usr/bin/mail -s "AIDE Report: $(hostname)" root
EOF
chmod +x /etc/cron.daily/aide-check

# ---------------------------------------------------------------------------
section "Motd / Banner"
# ---------------------------------------------------------------------------
cat > /etc/motd << EOF

  $(hostname -f) | $(lsb_release -ds)
  Kernel: $(uname -r) | Setup: $(date +%Y-%m-%d)
  Unauthorized access is prohibited and monitored.

EOF

# ---------------------------------------------------------------------------
section "Final Summary"
# ---------------------------------------------------------------------------
echo
echo "============================================================"
echo " SETUP COMPLETE: $(hostname)"
echo "============================================================"
echo " Admin user:   $ADMIN_USER"
echo " SSH port:     $SSHD_PORT"
echo " Timezone:     $TIMEZONE"
echo " UFW:          $(ufw status | head -1)"
echo " Fail2ban:     $(systemctl is-active fail2ban)"
echo " Auditd:       $(systemctl is-active auditd)"
echo " Log:          $LOG_FILE"
echo "============================================================"
echo
warn "Next steps:"
echo "  1. Add SSH public key to ~$ADMIN_USER/.ssh/authorized_keys"
echo "  2. Set PasswordAuthentication no in /etc/ssh/sshd_config.d/99-hardening.conf"
echo "  3. Test SSH login before closing this session"
echo "  4. Run: bash security/hardening/harden.sh for deeper hardening"
